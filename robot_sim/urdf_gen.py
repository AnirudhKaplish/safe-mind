"""Procedurally write ``urdf/companion.urdf`` and ``urdf/meshes/face_quad.obj``.

No external mesh assets. Frame convention: +X is the robot's front (towards
the clinician / default camera), +Z up. Final dimensions (metres) are
listed in ``DIMS`` and documented in docs/ROBOT_SIMULATION.md.
"""
from __future__ import annotations

from pathlib import Path

from . import config

DIMS = {
    "foot": (0.114, 0.094, 0.006),
    "base": (0.120, 0.100, 0.045),
    "led_ring": (0.012, 0.004),            # radius, height
    "pan_servo": (0.023, 0.012, 0.029),
    "neck": (0.030, 0.030, 0.050),
    "tilt_servo": (0.023, 0.012, 0.029),
    "head": (0.060, 0.090, 0.070),         # X depth, Y width, Z height
    "bezel": (0.004, 0.060, 0.036),
    "face": (0.050, 0.025),                # width (Y), height (Z)
}
FOOT_H = DIMS["foot"][2]
BASE_TOP = FOOT_H + DIMS["base"][2]        # 0.051
HEAD_GAP = 0.004                           # head bottom above the tilt axis
HEAD_CZ = HEAD_GAP + DIMS["head"][2] / 2   # head centre above tilt axis
FACE_CZ = HEAD_CZ + 0.004                  # face slightly above head centre

MASSES = {"base": 0.250, "led_ring": 0.002, "pan_servo": 0.009, "neck": 0.012,
          "tilt_servo": 0.009, "head": 0.045, "bezel": 0.004, "face": 0.001}

COLORS = {
    "shell": (0.93, 0.92, 0.89, 1), "foot": (0.62, 0.61, 0.58, 1),
    "servo": (0.15, 0.35, 0.75, 1), "neck": (0.55, 0.57, 0.57, 1),
    "bezel": (0.05, 0.05, 0.06, 1), "face": (1, 1, 1, 1), "led": (0.7, 0.7, 0.66, 1),
}


def _box_inertia(m, x, y, z):
    return (m * (y * y + z * z) / 12, m * (x * x + z * z) / 12, m * (x * x + y * y) / 12)


def _inertial(m, size, xyz=(0, 0, 0)):
    ixx, iyy, izz = _box_inertia(m, *size)
    return (f'<inertial><origin xyz="{_v(xyz)}"/><mass value="{m}"/>'
            f'<inertia ixx="{ixx:.3e}" iyy="{iyy:.3e}" izz="{izz:.3e}" ixy="0" ixz="0" iyz="0"/></inertial>')


def _v(t):
    return " ".join(f"{x:.5f}" for x in t)


def _mat(name):
    return f'<material name="{name}"><color rgba="{_v(COLORS[name])}"/></material>'


def _box(size, xyz, mat, collide=True):
    vis = f'<visual><origin xyz="{_v(xyz)}"/><geometry><box size="{_v(size)}"/></geometry>{_mat(mat)}</visual>'
    col = f'<collision><origin xyz="{_v(xyz)}"/><geometry><box size="{_v(size)}"/></geometry></collision>' if collide else ""
    return vis + col


def _link(name, body, mass, size, com=(0, 0, 0)):
    return f'<link name="{name}">{_inertial(mass, size, com)}{body}</link>'


def _joint(name, kind, parent, child, xyz, axis=None, limits=None):
    s = f'<joint name="{name}" type="{kind}"><parent link="{parent}"/><child link="{child}"/><origin xyz="{_v(xyz)}"/>'
    if axis:
        s += f'<axis xyz="{_v(axis)}"/>'
    if limits:
        lo, hi = limits
        s += (f'<limit lower="{lo:.4f}" upper="{hi:.4f}" effort="{config.SG90_STALL_TORQUE_NM:.4f}" '
              f'velocity="{config.SG90_MAX_RAD_S:.2f}"/>'
              f'<dynamics damping="{config.JOINT_DAMPING}" friction="0"/>')
    return s + "</joint>"


def face_obj() -> str:
    w, h = DIMS["face"]
    # Quad in the YZ plane facing +X. Viewer's right (from the front) is +Y,
    # so u grows with +Y; v grows with +Z.
    return "\n".join([
        "# face quad for the OLED texture (generated by robot_sim/urdf_gen.py)",
        f"v 0 {-w/2:.5f} {-h/2:.5f}", f"v 0 {w/2:.5f} {-h/2:.5f}",
        f"v 0 {w/2:.5f} {h/2:.5f}", f"v 0 {-w/2:.5f} {h/2:.5f}",
        "vt 0 0", "vt 1 0", "vt 1 1", "vt 0 1",
        "vn 1 0 0",
        "f 1/1/1 2/2/1 3/3/1", "f 1/1/1 3/3/1 4/4/1", "",
    ])


def urdf_xml() -> str:
    d = DIMS
    bx, by, bz = d["base"]
    psx, psy, psz = d["pan_servo"]
    nx, ny, nz = d["neck"]
    hx, hy, hz = d["head"]
    zx, zy, zz = d["bezel"]
    lim = (-1.5708, 1.5708)
    parts = ['<?xml version="1.0"?>', '<robot name="mhd_companion">']
    parts.append(_link("base",
                       _box(d["foot"], (0, 0, FOOT_H / 2), "foot")
                       + _box(d["base"], (0, 0, FOOT_H + bz / 2), "shell"),
                       MASSES["base"], d["base"], (0, 0, FOOT_H + bz / 2)))
    r, h = d["led_ring"]
    parts.append(_link("led_ring",
                       f'<visual><geometry><cylinder radius="{r}" length="{h}"/></geometry>{_mat("led")}</visual>',
                       MASSES["led_ring"], (2 * r, 2 * r, h)))
    parts.append(_joint("led_fixed", "fixed", "base", "led_ring", (bx / 2 - 0.022, 0, BASE_TOP + h / 2)))
    parts.append(_link("pan_servo", _box(d["pan_servo"], (0, 0, psz / 2), "servo", collide=False),
                       MASSES["pan_servo"], d["pan_servo"], (0, 0, psz / 2)))
    parts.append(_joint("pan_servo_fixed", "fixed", "base", "pan_servo", (-0.012, 0, BASE_TOP)))
    parts.append(_link("neck", _box(d["neck"], (0, 0, nz / 2), "neck"), MASSES["neck"], d["neck"], (0, 0, nz / 2)))
    parts.append(_joint("pan", "revolute", "pan_servo", "neck", (0, 0, psz), (0, 0, 1), lim))
    tx, ty, tz = d["tilt_servo"]
    parts.append(_link("tilt_servo", _box((tx, ty, tz), (0, 0, 0), "servo", collide=False),
                       MASSES["tilt_servo"], d["tilt_servo"]))
    parts.append(_joint("tilt_servo_fixed", "fixed", "neck", "tilt_servo", (0, ny / 2 + ty / 2, nz - tz / 2 + 0.004)))
    parts.append(_link("head", _box(d["head"], (0, 0, HEAD_CZ), "shell"), MASSES["head"], d["head"], (0, 0, HEAD_CZ)))
    parts.append(_joint("tilt", "revolute", "neck", "head", (0, 0, nz), (0, 1, 0), lim))
    parts.append(_link("bezel", _box(d["bezel"], (0, 0, 0), "bezel", collide=False), MASSES["bezel"], d["bezel"]))
    parts.append(_joint("bezel_fixed", "fixed", "head", "bezel", (hx / 2 + zx / 2, 0, FACE_CZ)))
    fw, fh = d["face"]
    parts.append(_link("face",
                       f'<visual><geometry><mesh filename="meshes/face_quad.obj" scale="1 1 1"/></geometry>{_mat("face")}</visual>',
                       MASSES["face"], (0.001, fw, fh)))
    parts.append(_joint("face_fixed", "fixed", "bezel", "face", (zx / 2 + 0.0005, 0, 0)))
    parts.append("</robot>")
    return "\n".join(parts) + "\n"


def write(urdf_dir: Path = config.URDF_DIR) -> Path:
    urdf_dir = Path(urdf_dir)
    (urdf_dir / "meshes").mkdir(parents=True, exist_ok=True)
    (urdf_dir / "meshes" / "face_quad.obj").write_text(face_obj())
    path = urdf_dir / "companion.urdf"
    path.write_text(urdf_xml())
    return path


if __name__ == "__main__":
    print(write())
